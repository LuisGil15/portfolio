import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {stripTypeScriptTypes} from 'node:module';

const source=stripTypeScriptTypes(fs.readFileSync(new URL('../src/scripts/portfolio-viewport-clip.ts',import.meta.url),'utf8'));
function setup({native=true,eligible=true,range=true}={}) {
  const listeners=new Map(),frames=[],observers=[],values=new Map();
  const viewport={dataset:{},style:{setProperty:(name,value)=>values.set(name,value)}};
  const boundary={dataset:{},style:{setProperty:(name,value)=>values.set(name,value)}};
  const spacer={};
  const document={documentElement:{scrollHeight:2800,clientHeight:800},querySelector:selector=>({'.portfolio-viewport':viewport,'.portfolio-paint-boundary':boundary,'.portfolio-header-spacer':spacer})[selector]};
  const window={scrollY:0,addEventListener:(name,fn)=>listeners.set(name,fn),visualViewport:{addEventListener(){}}};
  vm.runInNewContext(source,{document,window,location:{search:''},URLSearchParams,CSS:{supports:(name)=>name==='-webkit-touch-callout'?eligible:name==='animation-timeline'?native:name==='animation-range'?range:true},ResizeObserver:class{constructor(fn){observers.push(fn);}observe(){}},requestAnimationFrame:fn=>{frames.push(fn);return frames.length;}});
  return {listeners,frames,observers,values,viewport,boundary,document,window};
}
const native=setup();
assert.equal(native.viewport.dataset.safariClip,'native');
assert.equal(native.values.get('--portfolio-scroll-distance'),'2800px');
assert.equal(native.listeners.has('scroll'),false,'native scrolling must not depend on a scroll event callback');
assert.equal(native.frames.length,0,'native path must not schedule JS frames');
native.document.documentElement.scrollHeight=3400;
native.observers[0]();
assert.equal(native.values.get('--portfolio-scroll-distance'),'3400px','expanding content must update the timeline range');
const fallback=setup({native:false});
assert.equal(fallback.viewport.dataset.safariClip,'fallback');
fallback.window.scrollY=402;
fallback.listeners.get('scroll')();fallback.listeners.get('scroll')();
assert.equal(fallback.frames.length,1,'fallback must coalesce scroll updates');
fallback.frames.shift()();
assert.equal(fallback.values.get('--portfolio-clip-top'),'402px');
fallback.window.scrollY=-20;
fallback.listeners.get('pageshow')();
assert.equal(fallback.values.get('--portfolio-clip-top'),'0px');
const partial=setup({range:false});
assert.equal(partial.viewport.dataset.safariClip,'fallback','partial timeline support must not enable native transforms');
const normal=setup({eligible:false});
assert.equal(normal.viewport.dataset.safariClip,undefined);
assert.equal(normal.listeners.size,0);
console.log('Native scroll has no JS frame dependency; resize range, fallback coalescing and eligibility pass.');
